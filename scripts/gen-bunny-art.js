// Generates src/js/01b-bunny-art.js from the approved bunny SVGs in art/bunnies/.
//   node scripts/gen-bunny-art.js
// Each breed's body keeps its own art; the eyes are split out so any of the 4 eye styles can go on any breed.
// Element ids are stripped (many bunnies can be on one page); the unicorn's rainbow gradient gets a per-instance
// id (placeholder __UID__) so two rainbow bunnies never share/clash.
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const dir = path.join(root, "art", "bunnies");
const BREEDS = ["white", "brown", "patchy", "yellow", "pink", "dragon", "unicorn"];
const EYE_SOURCES = {plain: "brown", violet: "white", rose: "pink", stone: "dragon"};   // eye style -> file it's taken from
const read = b => fs.readFileSync(path.join(dir, `bunny_${b}.svg`), "utf8");
const inner = s => s.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
const eyeBlock = (s, side) => {
  const m = s.match(new RegExp(`<g id="eye-${side}">[\\s\\S]*?</g>(?=\\s*(<g id="eye-r">|<path id="whiskers"))`));
  if(!m) throw new Error("eye block not found: " + side);
  return m[0];
};
const viewBox = read("white").match(/viewBox="([^"]+)"/)[1];
const bodies = {}, eyes = {};
for(const b of BREEDS){
  let s = read(b);
  if(s.match(/viewBox="([^"]+)"/)[1] !== viewBox) throw new Error(b + ": viewBox differs");
  s = inner(s).replace(eyeBlock(s, "l"), "__EYES__").replace(eyeBlock(s, "r"), "");
  s = s.replace(/id="rainbow"/g, 'id="bnr__UID__"').replace(/url\(#rainbow\)/g, "url(#bnr__UID__)");
  s = s.replace(/\s+id="[a-z-]+"/g, "").replace(/\n\s*/g, "");
  bodies[b] = s;
}
for(const [style, b] of Object.entries(EYE_SOURCES)){
  const s = read(b);
  eyes[style] = (eyeBlock(s, "l") + eyeBlock(s, "r")).replace(/\s+id="[a-z-]+"/g, "");
}
const out = `  /* ---------------- Bunny art (GENERATED by scripts/gen-bunny-art.js from art/bunnies/ — don't edit) ---------------- */
  const BUNNY_BREEDS = ${JSON.stringify(BREEDS)};
  const BUNNY_EYES = ${JSON.stringify(Object.keys(EYE_SOURCES))};
  const BUNNY_NATIVE_EYES = {white: "violet", brown: "plain", patchy: "rose", yellow: "plain", pink: "rose", dragon: "stone", unicorn: "violet"};
  const BUNNY_VIEWBOX = ${JSON.stringify(viewBox)};
  const BUNNY_BODY = ${JSON.stringify(bodies)};
  const BUNNY_EYE_SVG = ${JSON.stringify(eyes)};
  let bunnyUid = 0;
  function bunnySVG(breed, eyeStyle){
    const body = BUNNY_BODY[breed] || BUNNY_BODY.white;
    const eye = BUNNY_EYE_SVG[eyeStyle] || BUNNY_EYE_SVG[BUNNY_NATIVE_EYES[breed] || "violet"];
    const uid = ++bunnyUid;
    return \`<svg viewBox="\${BUNNY_VIEWBOX}" xmlns="http://www.w3.org/2000/svg">\` + body.replace("__EYES__", eye).replace(/__UID__/g, uid) + "</svg>";
  }
`;
fs.writeFileSync(path.join(root, "src", "js", "01b-bunny-art.js"), out);
console.log("wrote src/js/01b-bunny-art.js (" + out.length + " chars)");
